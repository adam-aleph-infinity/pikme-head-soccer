function neonTowers(g, s, y0, count, seed, body, edge, lit, winStep) {
  const W = s.W;
  for (let i = 0; i < count; i++) {
    const w = 26 + rnd(seed + i) * 54;
    const x = i * (W / count) + (rnd(seed + i * 3) - 0.5) * 26;
    const h = 50 + rnd(seed + i * 7) * 165;
    R(g, x, y0 - h, w, h, body);
    R(g, x, y0 - h, 2, h, edge);                                   // lit left edge
    R(g, x, y0 - h, w, 2, edge);
    // Whether a window is lit is a hash of (cell, slow clock), so the building twinkles at
    // a human rate instead of every pane strobing in step.
    const cols = Math.max(1, (w / winStep) | 0), rows = Math.max(1, (h / (winStep + 2)) | 0);
    for (let cx = 0; cx < cols; cx++) {
      for (let cy = 0; cy < rows; cy++) {
        const k = (seed + i) * 977 + cx * 31 + cy;
        if (rnd2(k, ((s.t * 0.28 + rnd(k) * 9) | 0)) > 0.36) continue;
        R(g, x + 3 + cx * winStep, y0 - h + 4 + cy * (winStep + 2), winStep - 4, winStep - 3, lit[k % lit.length]);
      }
    }
    if (h > 170) {                                                  // aircraft warning light
      R(g, x + w / 2 - 1, y0 - h - 6, 2, 6, '#3a2f4e');
      if (Math.sin(s.t * 2.4 + i) > 0) R(g, x + w / 2 - 2, y0 - h - 9, 4, 4, '#ff3b3b');
    }
  }
}

function neonSign(g, s, x, y, i) {
  const h = 42 + (i % 3) * 22;
  R(g, x - 1, y - 1, 16, h + 2, '#0a0718');
  // A tube that is failing: the whole sign dims for a beat now and then. One dying sign in
  // a row of good ones is what sells a street as lived-in rather than art-directed.
  const dying = rnd(i * 7 + ((s.t * 9) | 0)) < 0.07;
  for (let k = 0; k < (h / 14) | 0; k++) {
    const chase = (((s.t * 3.4) | 0) + k) % 6 === 0;
    const c = dying ? '#2a2140' : (chase ? '#3a2f5e' : NEON_LIT[(i + k) % NEON_LIT.length]);
    R(g, x + 2, y + 3 + k * 14, 10, 10, c);
    R(g, x + 4, y + 5 + k * 14, 6, 2, dying ? '#2a2140' : '#ffffff');
  }
  R(g, x + 6, y - 10, 2, 10, '#2a2140');
}

