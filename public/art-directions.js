// Four ORIGINAL art directions for the backdrop — the move off the SF2 homage.
//
// The brief was "sharp, dense, many details, many moving background stuff", and the two
// faults in the stages this replaces are both structural, not stylistic:
//
//   1. ONE landmark on an empty sky. An SF2 backdrop gets away with that because it is
//      seen for 30 seconds; a stage you stare at for a whole match needs depth layers all
//      the way back, so the eye always has somewhere to go.
//   2. Two props moved. Everything else was a painting. A backdrop reads as ALIVE when
//      five or six unrelated systems are running at unrelated periods — that mismatch is
//      what makes it feel like a place rather than a wallpaper.
//
// So every direction here carries at least five independent animated systems, and the
// detail is generated by loops rather than hand-placed, which is the only way to get
// hundreds of small things out of a few dozen lines.
//
// Contract is identical to stages.js so these drop straight in:
//   draw(g, s)  where s = { W, t, crowd, horizon, crowdTop, crowdBot, gy }
// A direction owns sky → horizon → crowd band. game.js paints the railing, wall, hoardings,
// grass, goals and players on top, so nothing below crowdBot+8 survives — do not draw there.
// The top ~45 world px sit under the HUD in a real match, so no landmark goes up there.

const OUTLINE = '#0b0710';
const TAU = 6.2831853;

// ---- pixel helpers ---------------------------------------------------------
const R = (g, x, y, w, h, c) => { g.fillStyle = c; g.fillRect(Math.round(x), Math.round(y), Math.round(w), Math.round(h)); };
const OUT = (g, x, y, w, h, c) => { R(g, x - 1, y - 1, w + 2, h + 2, OUTLINE); R(g, x, y, w, h, c); };

// Flat colour bands, never a gradient. A gradient is the single fastest way to stop looking
// like a 16-bit game, and these backdrops live or die on reading as pixel art.
function bands(g, W, top, bot, colors) {
  const h = (bot - top) / colors.length;
  for (let i = 0; i < colors.length; i++) R(g, 0, top + i * h, W, h + 1, colors[i]);
}

// Layout "randomness" must be STABLE frame to frame or the whole backdrop strobes, so every
// scattered position here is a hash of an integer index — never Math.random(), which would
// re-roll 60 times a second and turn a skyline into television static.
function rnd(n) {
  let h = Math.imul(n ^ 0x9e3779b9, 0x85ebca6b);
  h ^= h >>> 13; h = Math.imul(h, 0xc2b2ae35); h ^= h >>> 16;
  return (h >>> 0) / 4294967296;
}
const rnd2 = (a, b) => rnd(Math.imul(a, 73856093) ^ Math.imul(b, 19349663));

const disc = (g, cx, cy, r, c) => { g.fillStyle = c; g.beginPath(); g.arc(Math.round(cx), Math.round(cy), r, 0, TAU); g.fill(); };
const ringS = (g, cx, cy, r, w, c) => { g.strokeStyle = c; g.lineWidth = w; g.beginPath(); g.arc(cx, cy, r, 0, TAU); g.stroke(); };
const poly = (g, pts, c) => {
  g.fillStyle = c; g.beginPath(); g.moveTo(pts[0][0], pts[0][1]);
  for (let i = 1; i < pts.length; i++) g.lineTo(pts[i][0], pts[i][1]);
  g.closePath(); g.fill();
};
// Wrap into [0,m) — every scrolling system here needs it and JS's % goes negative.
const wrap = (v, m) => ((v % m) + m) % m;

// A stand full of people, laid out on a GRID rather than scattered.
// The scatter the old stages used renders as confetti once the frame is downsampled 2x:
// 520 bodies over 960px is one every 1.8px, so they overlap into noise and the crowd stops
// reading as people at all. Placing them by index — row = i % rows, column = i / rows —
// gives 6 clean tiers of ~87, each body 5px wide with a 5px gap, which survives the
// downsample and reads as a crowd from across the room.
function tiers(g, s, o) {
  const rows = o.rows || 6;
  const top = s.crowdTop + 2, bot = s.crowdBot;
  const step = (bot - top - 14) / (rows - 1);
  const n = s.crowd.length, per = Math.ceil(n / rows), gap = s.W / per;
  const pal = o.pal, skin = o.skin || ['#f0b48a', '#d69a6e', '#a86a44'];
  for (let r = 0; r < rows; r++) {                                  // back row first
    const y = Math.round(top + r * step);
    R(g, 0, y + 13, s.W, 2, o.bench || '#00000044');                // the step they stand on
    for (let c = 0; c < per; c++) {
      const i = r * per + c;
      if (i >= n) break;
      const p = s.crowd[i];
      const k = (p.ph * 233 + i) | 0;
      const bob = Math.sin(s.t * (o.speed || 3) + p.ph) > 0.35 ? -2 : 0;
      const x = Math.round(c * gap + (rnd(i) - 0.5) * 4 + (r % 2) * gap * 0.5);
      R(g, x - 1, y + bob - 1, 7, 14, OUTLINE);
      R(g, x, y + bob + 4, 5, 9, pal[k % pal.length]);              // body
      R(g, x, y + bob, 5, 4, skin[k % skin.length]);                // head
      R(g, x, y + bob + 4, 5, 2, '#00000033');                      // shoulder shadow
      if (o.hat && rnd(k) < 0.34) R(g, x - 1, y + bob - 3, 7, 3, pal[(k + 3) % pal.length]);
      // one in fourteen has both arms up, which is what stops a grid reading as wallpaper
      if (rnd(k + 9) < 0.07) {
        const up = Math.sin(s.t * 2.6 + p.ph * 2) > 0 ? 4 : 0;
        R(g, x - 2, y + bob + 3 - up, 2, 6, skin[k % skin.length]);
        R(g, x + 5, y + bob + 3 - up, 2, 6, skin[k % skin.length]);
      }
      // and one in twenty is holding something up that POPS — phone, lamp, flare
      if (o.spark && rnd(k + 5) < 0.055) {
        R(g, x + 5, y + bob - 4, 2, 5, '#2a2a3a');
        if (Math.sin(s.t * 2.2 + p.ph * 3) > 0.7) R(g, x + 3, y + bob - 8, 5, 5, '#ffffff');
        else R(g, x + 4, y + bob - 7, 3, 3, o.spark);
      }
    }
  }
}

