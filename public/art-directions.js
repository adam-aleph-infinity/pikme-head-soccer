    // — 13. the crowd behind observation glass, helmet lamps blinking
    R(g, 0, hz + 4, W, cB + 10 - hz - 4, '#0d1024');
    R(g, 0, hz + 4, W, 4, '#3b4354');
    tiers(g, s, { rows: 6, pal: ['#4a5468', '#a8b2c0', '#2f56a0', '#c85a7a', '#3f9a86', '#d8a13c', '#6a6a90'], skin: ['#c4ccd8', '#8fb4d8'], bench: '#080a18', spark: '#23e6ff' });
