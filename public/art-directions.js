const LUNA_SKY = ['#3a2870', '#5e3286', '#8e3a86', '#c2497a', '#e86a5e', '#ff9a4a', '#ffc46a'];
const BULB = ['#fff3b0', '#ff4f9a', '#4fe0c0', '#ffd23c'];

// Coaster profile, hand-authored: two big hills and a bunny run. A sine wave reads as a
// graph; a hand-placed profile reads as a ride somebody designed.
const COASTER = [[-40, -34], [70, -104], [160, -52], [250, -136], [352, -168], [452, -96],
  [540, -150], [628, -66], [710, -112], [792, -48], [880, -92], [1000, -56]];
function coasterY(x) {
  for (let i = 0; i < COASTER.length - 1; i++) {
    const [x0, y0] = COASTER[i], [x1, y1] = COASTER[i + 1];
    if (x >= x0 && x <= x1) return y0 + (y1 - y0) * ((x - x0) / (x1 - x0));
  }
  return COASTER[COASTER.length - 1][1];
}

